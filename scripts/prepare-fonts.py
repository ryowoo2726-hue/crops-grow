"""Split the original variable font without dropping any supported characters.

Requires fonttools[woff] (build-time only). Hangul/Latin/symbols load at startup;
the original CJK ideographs load after the visible game assets.
"""
import hashlib
import re
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
source = root / 'assets/fonts/NotoSansKR.ttf'
original = TTFont(source).getBestCmap()
extended = {c for c in original if 0x3400 <= c <= 0x9FFF or 0xF900 <= c <= 0xFAFF}
groups = {'core': set(original) - extended, 'extended': extended}
assert set.union(*groups.values()) == set(original)
entries = []
assets = {}
for name, characters in groups.items():
    font = TTFont(source)
    options = subset.Options()
    options.layout_features = ['*']
    options.notdef_glyph = True
    options.recommended_glyphs = True
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=characters)
    sub.subset(font)
    assert set(font.getBestCmap()) == characters
    assert font['fvar'].axes[0].minValue == 100
    assert font['fvar'].axes[0].maxValue == 900
    font.flavor = 'woff2'
    import io
    data = io.BytesIO()
    font.save(data)
    content = data.getvalue()
    digest = hashlib.sha256(content).hexdigest()[:16]
    asset = f'assets/fonts/NotoSansKR-{name}-{digest}.woff2'
    (root / asset).write_bytes(content)
    entries.append(f"const {name}FontAsset = '{asset}';")
    assets[name] = asset
    print(f'{name}: {len(characters)} characters, {len(content):,} bytes', flush=True)
assert all(c in groups['core'] for c in range(0xAC00, 0xD7A4))
(root / 'lib/font_assets.dart').write_text(
    '// Generated by scripts/prepare-fonts.py. Original font and OFL are preserved.\n'
    + '\n'.join(entries) + '\n', encoding='utf-8')
manifest = root / 'pubspec.yaml'
text = manifest.read_text(encoding='utf-8')
text = re.sub(r'asset: assets/fonts/NotoSansKR[^\s]*\.woff2',
              'asset: ' + assets['core'], text)
text = re.sub(r'    - assets/fonts/NotoSansKR-extended[^\s]*\.woff2\n', '', text)
text = text.replace('    - assets/optimized/\n',
                    '    - assets/optimized/\n    - ' + assets['extended'] + '\n')
manifest.write_text(text, encoding='utf-8')
html = root / 'web/index.html'
html.write_text(re.sub(r'assets/assets/fonts/NotoSansKR[^\s\"\']*\.woff2',
                       'assets/' + assets['core'], html.read_text(encoding='utf-8')),
                encoding='utf-8')
